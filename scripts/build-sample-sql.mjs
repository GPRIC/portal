// Builds supabase/migrations/0002_sample_data.sql from the demo's fake database (data/db.js).
// Usage: node scripts/build-sample-sql.mjs <path to demo site>/data/db.js
// Every row is written with sample = true so "Clear Sample Data" can remove it.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const src = process.argv[2];
if (!src) { console.error('Pass the path to data/db.js'); process.exit(1); }
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(src, 'utf8'), ctx);
const db = ctx.window.GPRIC_DB;

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return v.length ? 'array[' + v.map(q).join(',') + ']::text[]' : "'{}'::text[]";
  if (typeof v === 'object') return q(JSON.stringify(v)) + '::jsonb';
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const out = [];
const insert = (table, rows, cols) => {
  if (!rows.length) return;
  out.push(`insert into public.${table} (${cols.join(', ')}, sample) values`);
  out.push(rows.map((r) => '  (' + cols.map((c) => q(r[c])).join(', ') + ', true)').join(',\n') + ';');
  out.push('');
};

const users = Object.fromEntries(db.users.map((u) => [u.id, u]));
const teamsById = Object.fromEntries(db.teams.map((t) => [t.id, t]));
const who = (id) => {
  const u = users[id]; if (!u) return id || null;
  const t = u.team_id ? teamsById[u.team_id] : null;
  return u.name + ' (' + u.title + (t ? ', ' + t.short : '') + ')';
};
const docLink = (href) => (href ? '/sample-docs/' + path.basename(href, '.html') : null);

const m = db.meta;
out.push('-- GPRIC Portal sample data, generated by scripts/build-sample-sql.mjs from the demo (fake names and figures only).');
out.push(`update public.settings set org = ${q(m.org)}, short = ${q(m.short)}, ein = ${q(m.ein)}, fy_start = ${q(m.fy_start)}, fy_label = ${q(m.fy_label)}, receipt_days = ${q(m.receipt_days)} where id = 1;`);
out.push('');

insert('funds', db.funds, ['id', 'name', 'restricted', 'team_id', 'purpose']);
insert('teams', db.teams, ['id', 'name', 'short', 'program', 'level', 'season', 'fund_id', 'pay_mode', 'ein', 'school', 'students', 'affiliated', 'blurb']);
insert('board_members', db.users.filter((u) => u.role === 'board').map((u, i) => ({ ...u, sort: (i + 1) * 10, interest_note: u.interest_note || null })),
  ['id', 'name', 'title', 'email', 'interest_team_id', 'interest_note', 'sort']);
insert('grants', db.grants_pipeline, ['id', 'funder', 'program', 'ask', 'awarded', 'received', 'status', 'deadline', 'applied_as', 'owner', 'board_saw', 'fund_id', 'purpose', 'public', 'likelihood', 'notes']);
insert('donors', db.donors.map((d) => ({ ...d, grant_id: d.grant_id || null })), ['id', 'name', 'type', 'giving', 'channel', 'anonymous', 'public', 'since', 'grant_id']);
insert('donations', db.donations.map((d) => ({ ...d, grant_id: d.grant_id || null })), ['id', 'donor_id', 'date', 'amount', 'fund_id', 'channel', 'recurring', 'grant_id', 'thanked']);

insert('meetings', db.meetings_votes.map((x) => ({
  ...x, summary: x.minutes,
  agenda_link: x.status === 'Scheduled' ? docLink(x.doc_href) : null,
  minutes_link: x.status === 'Scheduled' ? null : docLink(x.doc_href)
})), ['id', 'date', 'kind', 'title', 'status', 'present', 'summary', 'agenda_link', 'minutes_link']);

const votes = [];
let vn = 0;
db.meetings_votes.forEach((x) => x.votes.forEach((v, i) => {
  vn += 1;
  votes.push({ ...v, id: 'V-' + String(vn).padStart(3, '0'), meeting_id: x.id, request_id: v.request_id || null, sort: (i + 1) * 10, note: v.note || '' });
}));
const voteFor = (rid) => { const v = votes.filter((x) => x.request_id === rid); return v.length ? v[v.length - 1].id : null; };

insert('team_requests', db.team_requests.map((r) => ({ ...r, vote_id: voteFor(r.id), created_by: who(r.created_by), returned: r.returned || 0 })),
  ['id', 'team_id', 'purpose', 'category', 'amount', 'pay_to', 'needed_by', 'submitted', 'status', 'interested_member_id', 'vote_id', 'paid_date', 'receipts_done', 'returned', 'decline_reason', 'created_by']);
insert('meeting_votes', votes, ['id', 'meeting_id', 'item', 'request_id', 'result', 'yes', 'no', 'abstain', 'stepped_out', 'note', 'sort']);

insert('ledger', db.ledger.map((l) => ({
  ...l, donor_id: l.donation_id ? l.party : null, party: l.donation_id ? null : l.party, grant_id: l.grant_id || null
})), ['id', 'date', 'dir', 'amount', 'fund_id', 'source', 'category', 'party', 'donor_id', 'memo', 'donation_id', 'request_id', 'grant_id', 'receipt']);
// The ledger trigger adds grant payments to "received"; put the demo's figures back.
out.push('-- ledger inserts above raised grants.received through the trigger; restore the demo figures');
db.grants_pipeline.forEach((g) => out.push(`update public.grants set received = ${q(g.received)} where id = ${q(g.id)};`));
out.push('');

insert('receipts', db.receipts.map((r) => ({ ...r, file_name: r.file, uploaded_by: who(r.uploaded_by) })), ['id', 'request_id', 'vendor', 'amount', 'date', 'file_name', 'uploaded_by']);
insert('accounts', db.accounts_subscriptions, ['id', 'service', 'purpose', 'owner_email', 'admins', 'plan', 'cost', 'period', 'renewal', 'payment_method', 'discount', 'status']);
insert('documents', db.documents.map((d) => ({ ...d, link: docLink(d.href) })), ['id', 'title', 'type', 'date', 'linked_to', 'public', 'link', 'added_by']);

// Move each id sequence past the sample ids so new rows never collide.
const seqs = [['ledger', 'ledger_id_seq'], ['donations', 'donation_id_seq'], ['donors', 'donor_id_seq'], ['grants', 'grant_id_seq'],
  ['team_requests', 'request_id_seq'], ['receipts', 'receipt_id_seq'], ['meetings', 'meeting_id_seq'], ['meeting_votes', 'vote_id_seq'],
  ['accounts', 'account_id_seq'], ['documents', 'document_id_seq'], ['board_members', 'member_id_seq'], ['teams', 'team_id_seq'], ['funds', 'fund_id_seq']];
out.push('-- move id sequences past the sample ids');
seqs.forEach(([t, s]) => out.push(
  `select setval('public.${s}', greatest((select coalesce(max(nullif(regexp_replace(id, '\\D', '', 'g'), '')::bigint), 0) from public.${t} where id ~ '\\d$'), (select last_value from public.${s})));`));
out.push('');

const dest = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..', 'supabase', 'migrations', '0002_sample_data.sql');
fs.writeFileSync(dest, out.join('\n'));
console.log('Wrote', dest);
