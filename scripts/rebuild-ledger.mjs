// P23: rebuild the ledger from the bank lines.
// Reads private/statements/ledger-map.json (one entry per bank line: fund and what it was), bank-lines.json (the
// statements as parsed now) and bank-lines.loaded.json (the lines as first loaded), and writes
// private/statements/rebuild-ledger.sql. private/ is git-ignored: real data is never committed.
// The script, run once as the database owner:
//   1. corrects bank lines the first parse got wrong (amount or date; proved by the statements' daily balances),
//   2. books one ledger entry per bank line and matches the line to it; a Zeffy payout is matched to its payout
//      day's gifts instead (they are already in the books) and must equal them,
//   3. reverses the 2026-01-01 opening balances, which the 2025 bank lines now replace.
// It refuses to run twice, on a locked month, or if any line or payout does not match exactly.
// Usage: node scripts/rebuild-ledger.mjs
import fs from 'node:fs';
import path from 'node:path';

const DIR = path.resolve('private/statements');
const read = (f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
const now = read('bank-lines.json');
const loaded = read('bank-lines.loaded.json');
const map = read('ledger-map.json').lines;
const q = (s) => (s == null || s === '' ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

// 1. corrections: same month, same description, the amount or date differs
const fixes = [];
now.forEach((m, i) => m.lines.forEach((l, j) => {
  const o = loaded[i].lines[j];
  if (o.description !== l.description) throw new Error(`${m.month}: line order changed, cannot compare`);
  if (o.date !== l.date || o.amount !== l.amount) fixes.push({ month: m.month, description: l.description, from: o, to: l });
}));

// 2. every bank line has exactly one map entry, and every map entry exactly one bank line
const all = now.flatMap((m) => m.lines.map((l) => ({ ...l, month: m.month })));
const used = new Set();
for (const e of map) {
  const hits = all.filter((l, k) => !used.has(k) && l.date === e.date && Math.abs(l.amount - e.amount) < 0.005 && l.description.toUpperCase().includes(e.desc.toUpperCase()));
  if (hits.length < 1) throw new Error(`No bank line for ${e.date} ${e.amount} ${e.desc}`);
  const k = all.indexOf(hits[0]);
  used.add(k);
  e.description = hits[0].description;
  if (e.basis !== 'zeffy') {
    if (!e.fund) throw new Error(`${e.date} ${e.desc}: no fund`);
    if (e.amount < 0 && !e.category) throw new Error(`${e.date} ${e.desc}: money out needs a category`);
  }
}
if (used.size !== all.length) throw new Error(`${all.length - used.size} bank line(s) have no map entry: ` + all.filter((_, k) => !used.has(k)).map((l) => `${l.date} ${l.amount} ${l.description}`).join('; '));

const sql = [
  '-- GPRIC real books: the ledger rebuilt from the Citizens bank lines (generated by scripts/rebuild-ledger.mjs).',
  '-- Private: real bank data. Run once in the SQL editor, after load-bank-lines.sql.',
  'begin;',
  `select set_config('gpric.job', 'Ledger rebuild from bank statements', true), set_config('gpric.via', 'bank', true);`,
  `do $$ begin
  if exists (select 1 from public.bank_statements where locked_at is not null) then raise exception 'A month is already reconciled; the rebuild runs before any month is locked'; end if;
  if exists (select 1 from public.bank_lines where matched_ledger_id is not null or matched_payout_date is not null) then raise exception 'Bank lines are already matched; the rebuild has run'; end if;
  if (select count(*) from public.bank_lines where archived_at is null and not sample) <> ${all.length} then raise exception 'Expected ${all.length} bank lines'; end if;
end $$;`,
  '',
  '-- 1. bank lines the first parse got wrong (the daily balances on each statement prove these)',
];
for (const f of fixes) {
  sql.push(`do $$ declare n int; begin
  update public.bank_lines b set amount = ${f.to.amount.toFixed(2)}, date = ${q(f.to.date)}
    from public.bank_statements s
   where s.id = b.statement_id and s.month = ${q(f.month)} and b.description = ${q(f.description)} and b.amount = ${f.from.amount.toFixed(2)} and b.date = ${q(f.from.date)};
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'Correction for % matched % lines', ${q(f.description)}, n; end if;
end $$;`);
}

sql.push('', `select set_config('gpric.via', 'ledger', true);`, '-- 2. one ledger entry per bank line', `create temp table rebuild_map (
  n int, date date, amount numeric(12,2), description text, fund_id text, source text, category text, party text, memo text,
  pay_method text, pay_ref text, zeffy date, basis text) on commit drop;`);
sql.push('insert into rebuild_map values\n' + map.map((e, i) => `  (${i + 1}, ${q(e.date)}, ${e.amount.toFixed(2)}, ${q(e.description)}, ${q(e.fund)}, ${q(e.amount > 0 ? e.source : null)}, ${q(e.amount < 0 ? e.category : null)}, ${q(e.party)}, ${q(e.memo)}, ${q(e.pay_method)}, ${q(e.pay_ref)}, ${e.zeffy ? q(e.zeffy) + '::date' : 'null'}, ${q(e.basis)})`).join(',\n') + ';');
sql.push(`do $$
declare r record; b text; v text; z numeric;
begin
  for r in select * from rebuild_map order by n loop
    select bl.id into b from public.bank_lines bl
     where bl.archived_at is null and not bl.sample and bl.matched_ledger_id is null and bl.matched_payout_date is null
       and bl.date = r.date and bl.amount = r.amount and bl.description = r.description
     order by bl.id limit 1;
    if b is null then raise exception 'No bank line for % % %', r.date, r.amount, r.description; end if;
    if r.zeffy is not null then
      select coalesce(sum(d.amount), 0) into z from public.donations d where d.channel = 'Zeffy' and d.payout_date = r.zeffy and d.archived_at is null;
      if z <> r.amount then raise exception 'Zeffy payout % is % but its gifts come to %', r.zeffy, r.amount, z; end if;
      update public.bank_lines set matched_payout_date = r.zeffy where id = b;
    else
      insert into public.ledger (date, dir, amount, fund_id, source, category, party, memo, pay_method, pay_ref)
      values (r.date, case when r.amount > 0 then 'in' else 'out' end, abs(r.amount), r.fund_id, r.source, r.category, r.party,
              r.memo || case r.basis when 'carry-over' then ' (fund worked out from the 2025 carry-over)' when 'missing' then ' (missing information)' else '' end,
              r.pay_method, r.pay_ref)
      returning id into v;
      update public.bank_lines set matched_ledger_id = v where id = b;
    end if;
  end loop;
end $$;`);

sql.push('', '-- 3. the 2026-01-01 opening balances: the 2025 bank lines now carry that money, so each is reversed (same date)', `do $$
declare l public.ledger%rowtype; v text;
begin
  for l in select * from public.ledger where source = 'Opening Balance' and not sample and reverses_id is null and reversed_by_id is null order by id loop
    insert into public.ledger (date, dir, amount, fund_id, source, category, party, memo, reverses_id, reason, receipt)
    values (l.date, case l.dir when 'in' then 'out' else 'in' end, l.amount, l.fund_id, l.source, l.category, l.party,
            'Reversal of ' || l.id || coalesce(' · ' || l.memo, ''), l.id, 'Replaced by the 2025 bank lines (real books from March 2025)', true)
    returning id into v;
    update public.ledger set reversed_by_id = v, reason = 'Replaced by the 2025 bank lines (real books from March 2025)' where id = l.id;
  end loop;
end $$;`);
sql.push(`select set_config('gpric.job', '', true), set_config('gpric.via', '', true);`, 'commit;', '',
  '-- check: every line matched; each fund\'s real balance',
  `select (select count(*) from public.bank_lines where matched_ledger_id is null and matched_payout_date is null) unmatched_lines,
       (select jsonb_object_agg(f.name, (select coalesce(sum(case when l.dir = 'in' then l.amount else -l.amount end), 0) from public.ledger l where l.fund_id = f.id and not l.sample))
          from public.funds f where not f.sample) fund_balances;`);

fs.writeFileSync(path.join(DIR, 'rebuild-ledger.sql'), sql.join('\n') + '\n');
const by = map.reduce((t, e) => ((t[e.basis] = (t[e.basis] || 0) + 1), t), {});
console.log(`${fixes.length} bank line correction(s); ${map.length} lines: ${Object.entries(by).map(([k, v]) => `${v} ${k}`).join(', ')}. Written to private/statements/rebuild-ledger.sql.`);
